import { useEffect, useRef, useState } from 'react';
import { askAi } from '../api.js';
import { askSuggestions } from '../data/content.js';

const MAX_LENGTH = 500;
const HISTORY_LIMIT = 10; // messages sent back to the API for context

function friendlyError(err) {
  if (err.name === 'AbortError') return null;
  if (err.status === 429) return 'Too many questions in a short time. Wait a minute and try again.';
  if (err.status >= 500) return 'The AI service is not available right now. Try again shortly.';
  return err.message || 'Something went wrong. Try again.';
}

export default function AskBar() {
  const [open, setOpen] = useState(false);
  const [messages, setMessages] = useState([]); // { id, role, content }
  const [input, setInput] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [lastPrompt, setLastPrompt] = useState('');

  const inputRef = useRef(null);
  const logRef = useRef(null);
  const abortRef = useRef(null);
  const idRef = useRef(0);

  // Keep the newest message in view.
  useEffect(() => {
    const el = logRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages, loading, error, open]);

  // Escape closes the panel; cancel any in-flight request on unmount.
  useEffect(() => {
    const onKey = (e) => {
      if (e.key === 'Escape') setOpen(false);
    };
    window.addEventListener('keydown', onKey);
    return () => {
      window.removeEventListener('keydown', onKey);
      abortRef.current?.abort();
    };
  }, []);

  async function ask(text, base = messages) {
    const message = text.trim();
    if (!message || loading) return;

    const userMsg = { id: ++idRef.current, role: 'user', content: message };
    const history = base.slice(-HISTORY_LIMIT).map(({ role, content }) => ({ role, content }));

    setMessages([...base, userMsg]);
    setInput('');
    setError('');
    setLastPrompt(message);
    setOpen(true);
    setLoading(true);

    abortRef.current?.abort();
    const controller = new AbortController();
    abortRef.current = controller;

    try {
      const { answer } = await askAi({ message, history, signal: controller.signal });
      setMessages((m) => [...m, { id: ++idRef.current, role: 'assistant', content: answer }]);
    } catch (err) {
      const msg = friendlyError(err);
      if (msg) setError(msg);
    } finally {
      if (abortRef.current === controller) setLoading(false);
    }
  }

  function onSubmit(e) {
    e.preventDefault();
    ask(input);
  }

  function retry() {
    // Drop the failed user message, then send it again.
    const base = messages.slice(0, -1);
    setMessages(base);
    ask(lastPrompt, base);
  }

  function clear() {
    abortRef.current?.abort();
    setMessages([]);
    setError('');
    setLoading(false);
    inputRef.current?.focus();
  }

  const showPanel = open;

  return (
    <div className="ask" role="region" aria-label="Ask about this site">
      {showPanel && (
        <div className="ask__panel">
          <div className="ask__head">
            <h2 className="ask__title">Ask about this site</h2>
            <div className="ask__head-actions">
              {messages.length > 0 && (
                <button type="button" className="link-btn" onClick={clear}>Clear</button>
              )}
              <button type="button" className="link-btn" onClick={() => setOpen(false)} aria-label="Close conversation">
                Close
              </button>
            </div>
          </div>

          <div className="ask__log" ref={logRef} role="log" aria-live="polite" aria-relevant="additions">
            {messages.length === 0 && !loading && !error && (
              <div className="ask__empty">
                <p>Ask a question and get an answer based on what is on this site.</p>
                <ul className="ask__chips">
                  {askSuggestions.map((s) => (
                    <li key={s}>
                      <button type="button" onClick={() => ask(s)}>{s}</button>
                    </li>
                  ))}
                </ul>
              </div>
            )}

            {messages.map((m) => (
              <div key={m.id} className={`ask__msg ask__msg--${m.role}`}>
                <span className="visually-hidden">{m.role === 'user' ? 'You: ' : 'Answer: '}</span>
                {m.content}
              </div>
            ))}

            {loading && <div className="ask__msg ask__msg--assistant ask__thinking">Thinking</div>}

            {error && (
              <div className="ask__error" role="alert">
                <p>{error}</p>
                <button type="button" className="link-btn" onClick={retry}>Try again</button>
              </div>
            )}
          </div>

          <p className="ask__note">Answers are generated by AI and can be wrong.</p>
        </div>
      )}

      <form className="ask__bar" onSubmit={onSubmit}>
        <label htmlFor="ask-input" className="visually-hidden">Ask a question about this site</label>
        <input
          id="ask-input"
          ref={inputRef}
          type="text"
          value={input}
          maxLength={MAX_LENGTH}
          placeholder="Ask a question about this site"
          autoComplete="off"
          onChange={(e) => setInput(e.target.value)}
          onFocus={() => setOpen(true)}
        />
        <button type="submit" className="ask__send" disabled={loading || !input.trim()}>
          {loading ? 'Asking' : 'Ask'}
        </button>
      </form>
    </div>
  );
}
